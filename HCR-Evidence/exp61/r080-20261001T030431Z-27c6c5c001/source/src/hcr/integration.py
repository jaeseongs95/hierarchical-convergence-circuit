"""R0.3 typed 경로 메시지와 보수적인 통합. 신호값/참값을 타 처리기에 주입하지 않는다."""
from __future__ import annotations
from copy import deepcopy
from dataclasses import dataclass
from . import codec
from .model import ContractError, Observation, fingerprint

METHODS = ('sequential', 'associative')
PORT = 'public_path_hint_v1'


@dataclass(frozen=True)
class RouteHint:
    """sender가 실제 만든 경로. receiver의 기존 frontier 우선순위에만 사용한다."""
    sender: str
    receiver: str
    observation_digest: str
    observation_revision: int
    memory_digest: str
    path: tuple[int, ...]
    roles: tuple[tuple[str, str], ...]
    evidence_refs: tuple[str, ...]
    source_event_seq: int
    source_event_sha256: str
    source_generation: int
    port: str = PORT

    @property
    def id(self):
        return 'hint-' + fingerprint(codec.plain(self))

    def packet(self):
        return dict(id=self.id, **codec.plain(self))

    @classmethod
    def from_packet(cls, packet):
        try:
            raw = dict(packet)
            identity = raw.pop('id')
            hint = cls(**dict(raw, path=tuple(raw['path']),
                              roles=tuple(tuple(p) for p in raw['roles']),
                              evidence_refs=tuple(raw['evidence_refs'])))
            if identity != hint.id:
                raise ContractError('route hint checksum')
            return hint
        except (KeyError, TypeError, ValueError) as error:
            raise ContractError('malformed typed route hint') from error

    def validate(self, observation: Observation, memory_digest: str, events):
        if (self.sender not in METHODS or self.receiver not in METHODS or self.sender == self.receiver
                or self.port != PORT or self.observation_digest != observation.digest
                or type(self.observation_revision) is not int or self.observation_revision != observation.revision
                or self.memory_digest != memory_digest or not self.path
                or type(self.source_event_seq) is not int or not 0 <= self.source_event_seq < len(events)
                or type(self.source_generation) is not int or self.source_generation < 1):
            raise ContractError('stale or invalid route hint binding')
        current, vertices = observation.start, [observation.start]
        for slot in self.path:
            if type(slot) is not int or not 0 <= slot < len(observation.edges):
                raise ContractError('route hint edge slot')
            edge = observation.edges[slot]
            if edge.source != current or edge.target in vertices or current == observation.goal:
                raise ContractError('route hint is not a simple public path')
            current = edge.target
            vertices.append(current)
        roles = tuple((f'R{i}', name) for i, name in enumerate(vertices))
        refs = tuple(observation.digest + ':' + observation.edges[i].id for i in self.path)
        if self.roles != roles or self.evidence_refs != refs:
            raise ContractError('route hint role/semantic/evidence mismatch')
        source = events[self.source_event_seq]
        if (source['sha256'] != self.source_event_sha256 or source['event'] != 'r02_expansion'
                or not any(tuple(p['path']) == self.path for p in source['payload']['added'])):
            raise ContractError('route hint was not generated by the sender')


def hints_from_expansion(sender, receiver, observation, memory_digest, events, generation, start):
    """공개 경로를 새로 탐색하지 않고, 이번 전이의 실제 additions만 내보낸다."""
    result = []
    for event in events[start:]:
        if event['event'] != 'r02_expansion':
            continue
        primary = tuple(event['payload']['prefix']['path']) + tuple(event['payload']['candidate']['edges'])
        for prefix in event['payload']['added']:
            if tuple(prefix['path']) != primary:
                continue
            path = tuple(prefix['path'])
            hint = RouteHint(sender, receiver, observation.digest, observation.revision, memory_digest,
                path, tuple((f'R{i}', v) for i, v in enumerate(prefix['visited'])),
                tuple(observation.digest + ':' + observation.edges[i].id for i in path),
                event['seq'], event['sha256'], generation)
            hint.validate(observation, memory_digest, events)
            result.append(hint)
    return result


def integrate(decisions: dict, expected_methods: tuple[str, ...], observation: Observation) -> dict:
    """다수결/평균 activation이 아니다. 불일치·미완료는 보류하고 각 proof를 보존한다."""
    if set(decisions) - set(expected_methods):
        raise ContractError('unexpected decision source')
    values = {name: d['value'] for name, d in decisions.items()}
    all_done = set(decisions) == set(expected_methods)
    resolved = all_done and all(value is not None for value in values.values())
    same = resolved and len(set(values.values())) == 1
    if same:
        status = 'single_method' if len(expected_methods) == 1 else 'agreement'
        value = next(iter(values.values()))
    else:
        status = 'conflict_abstention' if len({v for v in values.values() if v is not None}) > 1 else 'incomplete_or_ambiguous'
        value = None
    refs, proofs = set(), {}
    for name, decision in decisions.items():
        if decision['observation_digest'] != observation.digest or decision['mode'] != 'frozen_eval':
            raise ContractError('integration observation/mode mismatch')
        if decision['value'] is False and not decision['graph_complete']:
            raise ContractError('negative decision without dependency coverage')
        if decision['value'] is not None and not decision['proof']['under_assumptions_valid']:
            raise ContractError('integration requires a constructed primitive proof')
        for edge, truth in decision['proof']['assumed_edges']:
            if type(truth) is not bool or edge not in {e.id for e in observation.edges}:
                raise ContractError('integration proof binding')
            refs.add(observation.digest + ':' + edge)
        proofs[name] = deepcopy(decision['proof'])
    return dict(value=value, status=status, component_values=values, all_methods_finished=all_done,
        supporting_decision_ids={k: v['id'] for k, v in decisions.items()},
        unique_evidence_refs=sorted(refs), component_proofs=proofs,
        evidence_count_is_confidence=False, fabricated_combined_proof=False,
        external_truth_used=False, memory_updated=False)
